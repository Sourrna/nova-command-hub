// Server-only Notion adapter. Read-only by default; writes are gated behind
// explicit approval and are NOT implemented in this MVP.
//
// Keys are read from process.env by callers and never returned, logged, or
// echoed in errors. The integration token is sent as a bearer token and is
// never stored in the browser, in Git, or in chat.

const NOTION_API = "https://api.notion.com/v1";
export const NOTION_VERSION = "2022-06-28";

export type NotionResult<T> =
  | { ok: true; data: T }
  | { ok: false; code: "missing" | "auth" | "rate" | "error"; error: string };

function classify(status: number): NotionResult<never> {
  if (status === 401 || status === 403) return { ok: false, code: "auth", error: "Notion rejected the integration token." };
  if (status === 429) return { ok: false, code: "rate", error: "Notion rate limited the request; try again later." };
  return { ok: false, code: "error", error: `Notion request failed (${status}).` };
}

async function request<T>(path: string, init: RequestInit, f: typeof fetch): Promise<NotionResult<T>> {
  try {
    const r = await f(`${NOTION_API}/${path}`, {
      ...init,
      headers: {
        ...init.headers,
        "Notion-Version": NOTION_VERSION,
        "Content-Type": "application/json",
      },
      signal: AbortSignal.timeout(10_000),
    });
    if (!r.ok) {
      const body = (await r.text()).slice(0, 300);
      console.error(`Notion [${r.status}]: ${body}`);
      return classify(r.status);
    }
    return { ok: true, data: (await r.json()) as T };
  } catch {
    return { ok: false, code: "error", error: "Notion unreachable or timed out." };
  }
}

export async function notionGet<T>(path: string, init: RequestInit = { method: "GET" }, f: typeof fetch = fetch): Promise<NotionResult<T>> {
  const key = process.env["NOTION_API_KEY"];
  if (!key) return { ok: false, code: "missing", error: "Notion integration not linked." };
  return request<T>(path, { ...init, headers: { ...init.headers, Authorization: `Bearer ${key}` } }, f);
}

/** Search pages and databases the integration can access. */
export async function notionSearch(query: string, f: typeof fetch = fetch): Promise<NotionResult<{ results: unknown[] }>> {
  return notionGet(`search?q=${encodeURIComponent(query)}&page_size=20`, { method: "GET" }, f);
}

/** Fetch a single page by ID, including its content blocks. */
export async function notionFetchPage(pageId: string, f: typeof fetch = fetch): Promise<NotionResult<{ id: string; properties: unknown; results?: unknown[] }>> {
  return notionGet(`pages/${pageId}`, { method: "GET" }, f);
}

/** List blocks (children) of a page or block. */
export async function notionListChildren(blockId: string, f: typeof fetch = fetch): Promise<NotionResult<{ results: unknown[] }>> {
  return notionGet(`blocks/${blockId}/children?page_size=100`, { method: "GET" }, f);
}

export interface NotionPageInput {
  title: string;
  body: string;
  databaseId?: string | undefined;
  /** Optional server-side idempotency key. When present, Notion's
   * Idempotency-Key header is sent so a retried request does not create a
   * duplicate page. Generated by the approval ledger, never by the client. */
  idempotencyKey?: string | undefined;
}

/** Create a page under a database (or a workspace page when no database is given).
 * Gated behind explicit approval; writes are NOT enabled by default. */
export async function notionCreatePage(input: NotionPageInput, f: typeof fetch = fetch): Promise<NotionResult<{ id: string }>> {
  const key = process.env["NOTION_API_KEY"];
  if (!key) return { ok: false, code: "missing", error: "Notion integration not linked." };
  const properties: Record<string, unknown> = input.databaseId
    ? { parent: { database: input.databaseId } }
    : { parent: { type: "page_id", page_id: "root" } };
  if (input.title.trim()) {
    properties["Name" as const] = input.databaseId
      ? { title: [{ text: { content: input.title.trim() } }] }
      : { title: [{ text: { content: input.title.trim() } }] };
  }
  const children = input.body.trim()
    ? [{ object: "block", type: "paragraph", paragraph: { rich_text: [{ type: "text", text: { content: input.body.trim() } }] } }]
    : [];
  const headers: Record<string, string> = {
    Authorization: `Bearer ${key}`,
    "Notion-Version": NOTION_VERSION,
    "Content-Type": "application/json",
  };
  if (input.idempotencyKey) headers["Idempotency-Key"] = input.idempotencyKey;
  try {
    const r = await f(`${NOTION_API}/pages`, {
      method: "POST",
      headers,
      body: JSON.stringify({ ...properties, children }),
      signal: AbortSignal.timeout(15_000),
    });
    if (!r.ok) {
      const body = (await r.text()).slice(0, 300);
      console.error(`Notion POST [${r.status}]: ${body}`);
      return classify(r.status);
    }
    const data = (await r.json()) as { id?: string };
    if (!data.id) return { ok: false, code: "error", error: "Notion returned no page id." };
    return { ok: true, data: { id: data.id } };
  } catch {
    return { ok: false, code: "error", error: "Notion unreachable or timed out." };
  }
}