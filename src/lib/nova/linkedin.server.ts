// Server-only LinkedIn adapter. Read-only by default; publishing is gated
// behind explicit approval and is NOT implemented in this MVP.
//
// The integration token is sent as a bearer token and is read from
// process.env by callers — never returned, logged, or echoed in errors.

const LINKEDIN_API = "https://api.linkedin.com/v2";

export type LinkedinResult<T> =
  | { ok: true; data: T }
  | { ok: false; code: "missing" | "auth" | "rate" | "error"; error: string };

function classify(status: number): LinkedinResult<never> {
  if (status === 401 || status === 403) return { ok: false, code: "auth", error: "LinkedIn rejected the integration token." };
  if (status === 429) return { ok: false, code: "rate", error: "LinkedIn rate limited the request; try again later." };
  return { ok: false, code: "error", error: `LinkedIn request failed (${status}).` };
}

async function request<T>(path: string, init: RequestInit, f: typeof fetch): Promise<LinkedinResult<T>> {
  try {
    const r = await f(`${LINKEDIN_API}/${path}`, {
      ...init,
      headers: {
        ...init.headers,
        "Content-Type": "application/json",
        "X-Restli-Protocol-Version": "2.0.0",
      },
      signal: AbortSignal.timeout(10_000),
    });
    if (!r.ok) {
      const body = (await r.text()).slice(0, 300);
      console.error(`LinkedIn [${r.status}]: ${body}`);
      return classify(r.status);
    }
    return { ok: true, data: (await r.json()) as T };
  } catch {
    return { ok: false, code: "error", error: "LinkedIn unreachable or timed out." };
  }
}

export async function linkedinGet<T>(path: string, init: RequestInit = { method: "GET" }, f: typeof fetch = fetch): Promise<LinkedinResult<T>> {
  const key = process.env["LINKEDIN_ACCESS_TOKEN"];
  if (!key) return { ok: false, code: "missing", error: "LinkedIn integration not linked." };
  return request<T>(path, { ...init, headers: { ...init.headers, Authorization: `Bearer ${key}` } }, f);
}

/** Fetch the organization pages the integration can see. */
export async function linkedinOrganizations(f: typeof fetch = fetch): Promise<LinkedinResult<{ elements: unknown[] }>> {
  return linkedinGet(
    "organizationalEntityAcls?q=organizationalEntity&projection=(*,elements*(organizationalTargeting~))&count=10",
    { method: "GET" },
    f,
  );
}

/** Fetch recent UGC posts for an organizational entity. */
export async function linkedinPosts(organizationalId: string, f: typeof fetch = fetch): Promise<LinkedinResult<{ elements: unknown[] }>> {
  return linkedinGet(
    `ugcPosts?q=ugcPosts&projection=(*,elements*(id,commentary,visibility,created~))&q=organizationalEntity&searchParams=(organizationalEntity:urn:li:organizationalEntity:${organizationalId})&count=10`,
    { method: "GET" },
    f,
  );
}

/** Fetch engagement metrics (likes / comments / shares) for an entity. */
export async function linkedinMetrics(organizationalId: string, f: typeof fetch = fetch): Promise<LinkedinResult<{ elements: unknown[] }>> {
  return linkedinGet(
    `socialActions?q=organizationalEntity&searchParams=(organizationalEntity:urn:li:organizationalEntity:${organizationalId})&projection=(*,elements*(organizationalTargeting~))&count=10`,
    { method: "GET" },
    f,
  );
}

/** Supported post visibilities for the UGC Posts API. */
export type LinkedinVisibility = "PUBLIC" | "CONNECTIONS";

export interface LinkedinPostInput {
  /** Author URN, e.g. `urn:li:person:1234` or `urn:li:organization:5678`. */
  author: string;
  visibility: LinkedinVisibility;
  /** Post commentary. LinkedIn enforces a 700-character limit per post. */
  commentary: string;
  /** Optional title (rendered as the first line when present). */
  title?: string | undefined;
  /** Optional server-side idempotency key. When present it is forwarded as the
   * `X-Restli-Protocol-Version`-compliant `Idempotency-Key` header so a retried
   * request does not create a duplicate post. Generated by the approval ledger,
   * never by the client. */
  idempotencyKey?: string | undefined;
}

const COMMENTARY_MAX = 700;
const AUTHOR_RE = /^urn:li:(person|organization):[1-9]\d*$/i;

export function isLinkedinAuthorUrn(value: string): boolean {
  return AUTHOR_RE.test(value.trim());
}

export function extractLinkedinAuthors(data: unknown): string[] {
  if (!data || typeof data !== "object" || !("elements" in data) || !Array.isArray(data.elements)) return [];
  const authors = new Set<string>();
  for (const element of data.elements) {
    if (!element || typeof element !== "object") continue;
    for (const key of ["organizationalTarget", "roleAssignee"]) {
      const value = (element as Record<string, unknown>)[key];
      if (typeof value === "string" && isLinkedinAuthorUrn(value)) authors.add(value);
    }
  }
  return [...authors];
}

export function validateLinkedinPost(input: LinkedinPostInput): { ok: true } | { ok: false; error: string } {
  if (typeof input.author !== "string" || !isLinkedinAuthorUrn(input.author)) {
    return { ok: false, error: "Author must be a valid LinkedIn URN (urn:li:person:… or urn:li:organization:…)." };
  }
  if (input.visibility !== "PUBLIC" && input.visibility !== "CONNECTIONS") {
    return { ok: false, error: "Visibility must be PUBLIC or CONNECTIONS." };
  }
  const commentary = (input.title ? `${input.title.trim()}\n\n` : "") + input.commentary;
  if (typeof input.commentary !== "string" || !commentary.trim()) {
    return { ok: false, error: "Commentary is required." };
  }
  if (commentary.length > COMMENTARY_MAX) {
    return { ok: false, error: `Post is too long (max ${COMMENTARY_MAX} characters including title).` };
  }
  return { ok: true };
}

/**
 * Publish a post via the official LinkedIn UGC Posts API
 * (`POST /v2/ugcPosts`). Requires the `w_member_social` permission.
 *
 * This is a WRITE and is never called without an explicit, server-side,
 * single-use approval grant. The adapter itself only validates format and
 * forwards credentials — it does not decide who may call it.
 */
export async function linkedinPublishPost(
  input: LinkedinPostInput,
  f: typeof fetch = fetch,
): Promise<LinkedinResult<{ id: string; url?: string }>> {
  const key = process.env["LINKEDIN_ACCESS_TOKEN"];
  if (!key) return { ok: false, code: "missing", error: "LinkedIn integration not linked." };
  const v = validateLinkedinPost(input);
  if (!v.ok) return { ok: false, code: "error", error: v.error };

  const commentary = (input.title ? `${input.title.trim()}\n\n` : "") + input.commentary.trim();
  const headers: Record<string, string> = {
    Authorization: `Bearer ${key}`,
    "Content-Type": "application/json",
    "X-Restli-Protocol-Version": "2.0.0",
  };
  if (input.idempotencyKey) headers["Idempotency-Key"] = input.idempotencyKey;
  try {
    const r = await f(`${LINKEDIN_API}/ugcPosts`, {
      method: "POST",
      headers,
      body: JSON.stringify({
        author: input.author.trim(),
        visibility: input.visibility,
        commentary,
        isDistributionShare: false,
      }),
      signal: AbortSignal.timeout(15_000),
    });
    if (!r.ok) {
      const body = (await r.text()).slice(0, 300);
      console.error(`LinkedIn POST [${r.status}]: ${body}`);
      if (r.status === 401 || r.status === 403) return { ok: false, code: "auth", error: "LinkedIn rejected the integration token or permission." };
      if (r.status === 429) return { ok: false, code: "rate", error: "LinkedIn rate limited the request; try again later." };
      return { ok: false, code: "error", error: `LinkedIn publish failed (${r.status}).` };
    }
    const data = (await r.json()) as { id?: string };
    if (!data.id) return { ok: false, code: "error", error: "LinkedIn returned no post id." };
    return { ok: true, data: { id: data.id, url: `https://www.linkedin.com/posts/${data.id}` } };
  } catch {
    return { ok: false, code: "error", error: "LinkedIn unreachable or timed out." };
  }
}